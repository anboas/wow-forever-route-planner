import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const tokens = JSON.parse(await readFile(path.join(root, "design/design-tokens.json"), "utf8"));
const { colors, geometry } = tokens;

const css = `/* Generated by npm run sync:design. Do not edit by hand. */
:root {
  --canvas: ${colors.canvas};
  --frame: ${colors.frame};
  --surface: ${colors.surface};
  --surface-2: ${colors.elevated};
  --surface-3: ${colors.raised};
  --line: ${colors.line};
  --line-soft: ${colors.lineSoft};
  --ink: ${colors.text};
  --muted: ${colors.muted};
  --gold: ${colors.gold};
  --gold-2: ${colors.goldBright};
  --gold-dark: ${colors.goldDark};
  --arcane: ${colors.blue};
  --success: ${colors.green};
  --success-surface: ${colors.successSurface};
  --success-line: ${colors.successLine};
  --danger: ${colors.red};
  --warning: ${colors.warning};
  --radius: ${geometry.radius}px;
  --radius-sm: ${geometry.radiusSmall}px;
  --control-height: ${geometry.webControlHeight}px;
}
`;

const rgb = (hex) => {
  const value = hex.slice(1);
  return [0, 2, 4].map((offset) => Number.parseInt(value.slice(offset, offset + 2), 16) / 255);
};
const luaColor = (hex) => `{ ${rgb(hex).map((value) => Number(value.toFixed(4))).join(", ")}, 1 }`;
const lua = `-- Generated by npm run sync:design. Do not edit by hand.
WFRP_THEME = {
  canvas = ${luaColor(colors.canvas)},
  frame = ${luaColor(colors.frame)},
  surface = ${luaColor(colors.surface)},
  elevated = ${luaColor(colors.elevated)},
  raised = ${luaColor(colors.raised)},
  line = ${luaColor(colors.line)},
  lineSoft = ${luaColor(colors.lineSoft)},
  text = ${luaColor(colors.text)},
  muted = ${luaColor(colors.muted)},
  gold = ${luaColor(colors.gold)},
  goldBright = ${luaColor(colors.goldBright)},
  goldDark = ${luaColor(colors.goldDark)},
  blue = ${luaColor(colors.blue)},
  green = ${luaColor(colors.green)},
  red = ${luaColor(colors.red)},
  warning = ${luaColor(colors.warning)},
}
WFRP_DIMENSIONS = {
  frameWidth = ${geometry.addonFrameWidth}, frameHeight = ${geometry.addonFrameHeight}, sidebarWidth = ${geometry.addonSidebarWidth},
  tabHeight = ${geometry.addonTabHeight}, buttonHeight = ${geometry.addonButtonHeight}, metricHeight = ${geometry.addonMetricHeight},
  hudWidth = ${geometry.addonHudWidth}, hudHeight = ${geometry.addonHudHeight},
}
`;

await writeFile(path.join(root, "src/design-tokens.css"), css);
await writeFile(path.join(root, "addon/ForeverRouteCompanion/Theme.lua"), lua);
process.stdout.write("Synchronized website and addon design tokens.\n");
