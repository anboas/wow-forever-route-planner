import { execFile } from "node:child_process";
import { mkdir, rename, unlink, writeFile } from "node:fs/promises";
import { promisify } from "node:util";
import { fileURLToPath } from "node:url";
import path from "node:path";
import snapshot from "../src/data/wow-forever.json" with { type: "json" };
import context from "../src/data/wowf-context.json" with { type: "json" };

const execFileAsync = promisify(execFile);
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const addonDir = path.join(root, "addon/ForeverRouteCompanion");
const dataPath = path.join(addonDir, "Data.lua");
const publicDir = path.join(root, "public/addons");
const archivePath = path.join(publicDir, "ForeverRouteCompanion.zip");

const dungeonQuestIds = [...new Set([
  ...snapshot.dungeons.flatMap((dungeon) => dungeon.quests.map((quest) => Number(quest.id))),
  ...context.quests.filter((quest) => quest.stages.some((stage) => stage.dungeon?.name)).map((quest) => Number(quest.id)),
].filter((id) => Number.isInteger(id) && id > 0))].sort((a, b) => a - b);

const dungeonLines = snapshot.dungeons
  .slice()
  .sort((a, b) => a.id.localeCompare(b.id))
  .map((dungeon) => `[${JSON.stringify(dungeon.id)}]=${JSON.stringify(dungeon.name)}`);
const dungeonByNameLines = snapshot.dungeons
  .slice()
  .sort((a, b) => a.name.localeCompare(b.name))
  .map((dungeon) => `[${JSON.stringify(dungeon.name.toLowerCase())}]=${JSON.stringify(dungeon.id)}`);
const dungeonBossLines = snapshot.dungeons
  .slice()
  .sort((a, b) => a.id.localeCompare(b.id))
  .map((dungeon) => `[${JSON.stringify(dungeon.id)}]={${(dungeon.bosses || []).map((boss) => JSON.stringify(boss.name)).join(",")}}`);
const dungeonQuestLines = snapshot.dungeons
  .slice()
  .sort((a, b) => a.id.localeCompare(b.id))
  .map((dungeon) => `[${JSON.stringify(dungeon.id)}]={${dungeon.quests.map((quest) => Number(quest.id)).filter((id) => Number.isInteger(id) && id > 0).join(",")}}`);
const questLines = snapshot.dungeons
  .flatMap((dungeon) => dungeon.quests.map((quest) => {
    const giver = quest.from?.[0] || {};
    return `[${Number(quest.id)}]={name=${JSON.stringify(quest.name)},dungeon=${JSON.stringify(dungeon.id)},level=${Number(quest.minLevel ?? quest.level ?? dungeon.level[0]) || 1},faction=${JSON.stringify(quest.faction || "both")},giver=${JSON.stringify(giver.name || "")},zone=${JSON.stringify(giver.zone || dungeon.location || "")}}`;
  }))
  .filter((line) => !line.startsWith("[NaN]"));
const seenItems = new Set();
const itemLines = snapshot.dungeons.flatMap((dungeon) => dungeon.loot.map((item) => {
  const id = Number(item.id);
  if (!Number.isInteger(id) || id <= 0 || seenItems.has(id)) return null;
  seenItems.add(id);
  return `[${id}]={name=${JSON.stringify(item.name)},dungeon=${JSON.stringify(dungeon.id)},boss=${JSON.stringify(item.boss || "")},slot=${JSON.stringify(item.slot || item.type || "")}}`;
})).filter(Boolean);
const data = [
  "-- Generated by npm run sync:addon. Do not edit by hand.",
  `WFRP_DATA_FETCHED_AT=${JSON.stringify(snapshot.fetchedAt)}`,
  `WFRP_DATA_VERSION=${JSON.stringify(`forever-${snapshot.fetchedAt}`)}`,
  `WFRP_DUNGEON_QUEST_IDS={${dungeonQuestIds.map((id) => `[${id}]=true`).join(",")}}`,
  `WFRP_DUNGEONS={${dungeonLines.join(",")}}`,
  `WFRP_DUNGEONS_BY_NAME={${dungeonByNameLines.join(",")}}`,
  `WFRP_DUNGEON_BOSSES={${dungeonBossLines.join(",")}}`,
  `WFRP_DUNGEON_QUESTS={${dungeonQuestLines.join(",")}}`,
  `WFRP_QUESTS={${questLines.join(",")}}`,
  `WFRP_ITEMS={${itemLines.join(",")}}`,
  "",
].join("\n");

await mkdir(publicDir, { recursive: true });
const temporaryDataPath = `${dataPath}.tmp`;
await writeFile(temporaryDataPath, data);
await rename(temporaryDataPath, dataPath);
await unlink(archivePath).catch((error) => { if (error.code !== "ENOENT") throw error; });
await execFileAsync("zip", ["-q", "-r", archivePath, "ForeverRouteCompanion"], { cwd: path.dirname(addonDir) });
process.stdout.write(`Wrote ${dungeonQuestIds.length} quest IDs, ${itemLines.length} items, and ${snapshot.dungeons.length} dungeons to the companion addon.\n`);
