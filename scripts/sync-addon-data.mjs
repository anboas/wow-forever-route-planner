import { execFile } from "node:child_process";
import { mkdir, rename, unlink, writeFile } from "node:fs/promises";
import { promisify } from "node:util";
import { fileURLToPath } from "node:url";
import path from "node:path";
import snapshot from "../src/data/wow-forever.json" with { type: "json" };
import context from "../src/data/wowf-context.json" with { type: "json" };

const execFileAsync = promisify(execFile);
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const addonDir = path.join(root, "addon/ForeverRouteCompanion");
const dataPath = path.join(addonDir, "Data.lua");
const publicDir = path.join(root, "public/addons");
const archivePath = path.join(publicDir, "ForeverRouteCompanion.zip");

const dungeonQuestIds = [...new Set([
  ...snapshot.dungeons.flatMap((dungeon) => dungeon.quests.map((quest) => Number(quest.id))),
  ...context.quests.filter((quest) => quest.stages.some((stage) => stage.dungeon?.name)).map((quest) => Number(quest.id)),
].filter((id) => Number.isInteger(id) && id > 0))].sort((a, b) => a - b);

const dungeonLines = snapshot.dungeons
  .slice()
  .sort((a, b) => a.id.localeCompare(b.id))
  .map((dungeon) => `[${JSON.stringify(dungeon.id)}]=${JSON.stringify(dungeon.name)}`);
const data = [
  "-- Generated by npm run sync:addon. Do not edit by hand.",
  `WFRP_DATA_FETCHED_AT=${JSON.stringify(snapshot.fetchedAt)}`,
  `WFRP_DUNGEON_QUEST_IDS={${dungeonQuestIds.map((id) => `[${id}]=true`).join(",")}}`,
  `WFRP_DUNGEONS={${dungeonLines.join(",")}}`,
  "",
].join("\n");

await mkdir(publicDir, { recursive: true });
const temporaryDataPath = `${dataPath}.tmp`;
await writeFile(temporaryDataPath, data);
await rename(temporaryDataPath, dataPath);
await unlink(archivePath).catch((error) => { if (error.code !== "ENOENT") throw error; });
await execFileAsync("zip", ["-q", "-r", archivePath, "ForeverRouteCompanion"], { cwd: path.dirname(addonDir) });
process.stdout.write(`Wrote ${dungeonQuestIds.length} quest IDs and ${snapshot.dungeons.length} dungeons to the companion addon.\n`);
